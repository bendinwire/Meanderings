// node proto/build.js -> content/proto-{easy,medium,hard}.json and ../test-words.js (the /test/ page plays these).
const fs = require("fs"), path = require("path"), spec = require("./spec");
const out = {};
for (const d of Object.keys(spec)) out[d] = spec[d].map(c => {
  if (c.theme.length !== 8 || c.words.length !== 9) throw new Error("bad chain " + c.theme);
  return { bonus: { answer: c.theme, clue: c.clue }, words: c.words.map(([word, clue, plain], i) => {
    const e = { word, clue }; if (i) e.link = c.theme[i - 1]; if (plain) e.plain = plain; return e; }) };
});
const root = path.resolve(__dirname, "../..");
for (const d in out) fs.writeFileSync(path.join(__dirname, `../proto-${d}.json`), JSON.stringify(out[d], null, 1));
fs.writeFileSync(path.join(root, "theme-words.js"), "// Theme chains (generated by content/proto/build.js): link = 1 letter for every difficulty; the 8 gold letters spell the\n// theme that all nine words relate to. Difficulty is word/clue difficulty. Plays on puzzle days 3-7 (Nov 7-11) (see THEME_FROM_DAY in game.js).\nconst THEME_POOLS = " + JSON.stringify(out, null, 1) + ";\n\nif (typeof module !== \"undefined\") module.exports = THEME_POOLS;\n");
console.log("built", Object.entries(out).map(([d, p]) => d + ":" + p.length).join(" "));
